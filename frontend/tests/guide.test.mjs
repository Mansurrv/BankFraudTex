const origin=process.env.ORBIT_TEST_URL||'http://127.0.0.1:5173'
async function inBrowser(run,mobile=false) {
  const browser=await chromium.launch({
    channel:process.env.ORBIT_TEST_CHROME_CHANNEL||undefined,
    headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']
  })
  try {
    const page=await browser.newPage({viewport:mobile?{width:390,height:844}:{width:1440,height:920},acceptDownloads:true,reducedMotion:'reduce'})
    const errors=[]
    page.on('pageerror',error=>errors.push(error.message))
    page.setDefaultTimeout(10000)
    await page.goto(origin,{waitUntil:'domcontentloaded'})
    await page.getByRole('dialog',{name:'Welcome to FFBI'}).waitFor()
    await run(page)
    assert.deepEqual(errors,[])
  }finally{await browser.close()}
}
